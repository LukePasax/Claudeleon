// Il ponte fra la pagina e il processo principale: solo queste funzioni, niente accesso diretto a Node
const { contextBridge, ipcRenderer, webUtils } = require('electron')

const listen = (channel) => (cb) => ipcRenderer.on(channel, (_e, payload) => cb(payload))

contextBridge.exposeInMainWorld('skins', {
  info: () => ipcRenderer.invoke('app:info'),
  setInteractive: (on) => ipcRenderer.send('mouse:interactive', on),
  gestureStart: (kind) => ipcRenderer.send('gesture:start', kind),
  gestureEnd: () => ipcRenderer.send('gesture:end'),
  hide: () => ipcRenderer.send('window:hide'),
  windowMode: (mode) => ipcRenderer.send('window:mode', mode),
  chooseWorkdir: () => ipcRenderer.invoke('workdir:choose'),
  setWorkdir: (dir) => ipcRenderer.invoke('workdir:set', dir),
  windowState: () => ipcRenderer.invoke('window:state'),
  quit: () => ipcRenderer.send('app:quit'),
  setScene: (scene) => ipcRenderer.send('scene:set', scene),
  setTheme: (id) => ipcRenderer.send('theme:set', id),
  setMode: (mode) => ipcRenderer.send('mode:set', mode),
  openLink: (url) => ipcRenderer.send('link:open', url),
  newChapter: () => ipcRenderer.invoke('chapter:new'),
  send: (msg) => ipcRenderer.send('chat:send', msg),
  // Gli allegati: il percorso sul disco di un file trascinato o incollato (vuoto se non ne ha), la scelta dal disco,
  // la lettura di un'immagine
  pathForFile: (file) => { try { return webUtils.getPathForFile(file) || '' } catch { return '' } },
  chooseFiles: () => ipcRenderer.invoke('files:choose'),
  readImage: (p) => ipcRenderer.invoke('file:image', p),
  stop: () => ipcRenderer.send('chat:stop'),
  setTrayIcon: (dataUrl) => ipcRenderer.send('tray:icon', dataUrl),
  answer: (id, allow, always, answers) => ipcRenderer.send('perm:answer', { id, allow, always, answers }),
  // Modello e ragionamento
  models: () => ipcRenderer.invoke('models:get'),
  setModel: (model, effort) => ipcRenderer.send('model:set', { model, effort }),
  onModels: listen('models:list'),
  onTodos: listen('claude:todos'),
  onBusy: listen('claude:busy'),
  sessions: () => ipcRenderer.invoke('sessions:list'),
  commands: () => ipcRenderer.invoke('commands:get'),
  openSession: (id, cwd) => ipcRenderer.invoke('session:open', id, cwd),
  onAsk: listen('perm:ask'),
  onAskClosed: listen('perm:closed'),

  onDelta: listen('claude:delta'),
  onTool: listen('claude:tool'),
  onToolDone: listen('claude:toolDone'),
  onDone: listen('claude:done'),
  onError: listen('claude:error'),
  onReset: listen('chat:reset'),
  onTheme: listen('theme:apply'),
  onWindowState: listen('window:state'),
  onMode: listen('mode:changed'),
  onWorkdir: listen('workdir:changed'),
  onCommands: listen('commands:list'),
  onCommandsError: listen('commands:error'),
  onCommandOutput: listen('claude:commandOutput'),
  onToolSummary: listen('claude:toolSummary'),
  onCompacted: listen('claude:compacted'),
  onTitle: listen('claude:title'),
  onStatus: listen('claude:status'),
})
